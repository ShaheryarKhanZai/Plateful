#!/usr/bin/env python3
"""Run several copies of the API behind a load balancer, and keep them all alive.

    python cluster\\run_cluster.py                      # 3 instances on 8001-8003, load balancer on 8000
    python cluster\\run_cluster.py --instances 4
    python cluster\\run_cluster.py --chaos-every 15     # also crash a random instance every ~15 s (demo)

What it does
  1. starts N copies of the API (ports 8001, 8002, ...), each with its own share of database connections
  2. writes cluster/Caddyfile.generated and starts Caddy as the load balancer (port 8000)
  3. watches every process: if an instance crashes it is restarted after a short delay,
     and meanwhile Caddy sends all traffic to the instances that are still healthy

Point the frontend (VITE_API_URL) and the load-test programs at the load balancer, http://localhost:8000.
Run this with the backend's virtual environment active, so every instance uses the same Python.
"""
from __future__ import annotations

import argparse
import os
import random
import shutil
import signal
import socket
import subprocess
import sys
import time
import urllib.request
from datetime import datetime
from pathlib import Path

HERE = Path(__file__).resolve().parent
ROOT = HERE.parent
BACKEND = ROOT / "backend"
IS_WINDOWS = os.name == "nt"


def say(msg: str) -> None:
    print(f"[{datetime.now():%H:%M:%S}] {msg}", flush=True)


def die(msg: str) -> None:
    print(f"\nError: {msg}")
    sys.exit(2)


# --------------------------------------------------------------------------- helpers
def find_caddy(choice: str) -> str | None:
    found = shutil.which(choice)
    if found:
        return found
    if Path(choice).exists():
        return str(Path(choice))
    for name in ("caddy.exe", "caddy"):  # a copy placed next to this script also works
        if (HERE / name).exists():
            return str(HERE / name)
    return None


def port_in_use(host: str, port: int) -> bool:
    with socket.socket() as s:
        s.settimeout(0.3)
        return s.connect_ex((host, port)) == 0


def http_ready(host: str, port: int, path: str = "/health/ready") -> bool:
    try:
        with urllib.request.urlopen(f"http://{host}:{port}{path}", timeout=0.6) as r:
            return r.status == 200
    except Exception:
        return False


def tail(path: Path, lines: int = 8) -> str:
    try:
        return "\n".join("    " + ln for ln in path.read_text(errors="replace").splitlines()[-lines:])
    except OSError:
        return "    (no log)"


def build_caddyfile(host: str, lb_port: int, ports: list[int], policy: str, frontend_origin: str) -> str:
    upstreams = " ".join(f"{host}:{p}" for p in ports)
    return f"""# Generated by run_cluster.py. Do not edit: your changes are overwritten on the next start.
{{
	auto_https off
	admin localhost:2019
}}

:{lb_port} {{
	# Listen on this computer only (like the API did before). Remove this line to allow other devices.
	bind {host}

	reverse_proxy {upstreams} {{
		# Which instance gets the next request. least_conn = the one with the fewest requests in flight.
		lb_policy {policy}

		# If an instance cannot be reached, quietly try the others for up to this long.
		lb_try_duration 6s
		lb_try_interval 200ms

		# Active health check: ask every instance "can you reach the database?" every 2 seconds.
		# An instance that fails (or is down) gets no traffic until it answers 200 again.
		health_uri /health/ready
		health_interval 2s
		health_timeout 1s

		# Passive check: if a connection to an instance fails, skip it for 3 seconds (short, so an
		# instance that has been restarted rejoins quickly; the active check above does the rest).
		fail_duration 3s
		max_fails 1

		transport http {{
			dial_timeout 2s
		}}
	}}

	# If NO instance can answer, return the same JSON error shape as the API
	# (the frontend shows the message), with CORS headers so the browser can read it.
	handle_errors {{
		@unavailable expression {{err.status_code}} in [502, 503, 504]
		handle @unavailable {{
			header Content-Type application/json
			header Access-Control-Allow-Origin "{frontend_origin}"
			header Access-Control-Allow-Credentials true
			header Vary Origin
			respond `{{"error":{{"code":"unavailable","message":"The service is temporarily unavailable. Please try again in a moment."}}}}` {{err.status_code}}
		}}
	}}
}}
"""


# --------------------------------------------------------------------------- one managed process
class Managed:
    """A child process that we start, watch and restart."""

    def __init__(self, name: str, cmd: list[str], cwd: Path, env: dict, log_path: Path,
                 restart_delay: float, port: int | None = None) -> None:
        self.name, self.cmd, self.cwd, self.env, self.log_path = name, cmd, cwd, env, log_path
        self.restart_delay, self.port = restart_delay, port
        self.proc: subprocess.Popen | None = None
        self.started_at = 0.0
        self.down_since: float | None = None
        self.restarts = 0
        self.fast_failures = 0
        self.given_up = False

    def start(self) -> None:
        log = open(self.log_path, "ab")
        kw = {"creationflags": subprocess.CREATE_NEW_PROCESS_GROUP} if IS_WINDOWS else {"start_new_session": True}
        self.proc = subprocess.Popen(self.cmd, cwd=self.cwd, env=self.env, stdout=log, stderr=subprocess.STDOUT, **kw)
        self.started_at = time.monotonic()
        self.down_since = None

    def alive(self) -> bool:
        return self.proc is not None and self.proc.poll() is None

    def kill(self) -> None:
        if self.alive():
            self.proc.kill()

    def stop(self) -> None:
        if self.alive():
            self.proc.terminate()

    def supervise(self, now: float) -> None:
        """Restart the process after a short delay if it died. Give up if it dies instantly, repeatedly."""
        if self.alive() or self.given_up:
            return
        if self.down_since is None:
            self.down_since = now
            code = self.proc.poll() if self.proc else None
            self.fast_failures = self.fast_failures + 1 if now - self.started_at < 5 else 0
            if self.fast_failures >= 5:
                self.given_up = True
                say(f"{self.name} keeps crashing right after it starts, so it is NOT restarted again. Last log lines:\n{tail(self.log_path)}")
            else:
                say(f"{self.name} STOPPED (exit code {code}). Restarting in {self.restart_delay:g}s. Traffic goes to the others.")
        elif now - self.down_since >= self.restart_delay:
            self.start()
            self.restarts += 1
            say(f"{self.name} restarted (restart #{self.restarts}). It receives traffic again once its health check passes.")


# --------------------------------------------------------------------------- main
def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--instances", type=int, default=3, help="how many copies of the API to run (default %(default)s)")
    ap.add_argument("--base-port", type=int, default=8001, help="first instance port; the others follow (default %(default)s)")
    ap.add_argument("--lb-port", type=int, default=8000, help="load balancer port, the one clients use (default %(default)s)")
    ap.add_argument("--host", default="127.0.0.1", help="address the instances listen on (default %(default)s)")
    ap.add_argument("--policy", default="least_conn", choices=["least_conn", "round_robin", "random", "first"],
                    help="how the load balancer picks an instance (default %(default)s)")
    ap.add_argument("--caddy", default="caddy", help="caddy program name or path (default: caddy on PATH, or cluster/caddy.exe)")
    ap.add_argument("--frontend-origin", default="http://localhost:5173", help="must match FRONTEND_ORIGIN in backend/.env")
    ap.add_argument("--db-connections", type=int, default=80,
                    help="total database connections to share between instances; PostgreSQL allows 100 by default (default %(default)s)")
    ap.add_argument("--restart-delay", type=float, default=2.0, help="seconds to wait before restarting a crashed instance (default %(default)s)")
    ap.add_argument("--chaos-every", type=float, default=0, help="demo: hard-kill a random healthy instance about every N seconds (0 = off)")
    ap.add_argument("--status-every", type=float, default=10, help="seconds between status lines (default %(default)s)")
    ap.add_argument("--no-access-log", action="store_true", help="do not log every request (smaller log files)")
    ap.add_argument("--log-dir", type=Path, default=ROOT / "logs", help="where logs go (default %(default)s)")
    args = ap.parse_args()

    if args.instances < 1:
        die("--instances must be at least 1")
    if not (BACKEND / "app" / "main.py").exists():
        die(f"Cannot find the backend at {BACKEND}")
    caddy = find_caddy(args.caddy)
    if not caddy:
        die("Caddy (the load balancer) is not installed or not on PATH.\n"
            "  Windows:  winget install CaddyServer.Caddy      (then open a NEW terminal)\n"
            "  or download caddy_..._windows_amd64.zip from https://github.com/caddyserver/caddy/releases\n"
            "  and put caddy.exe in the cluster folder. See cluster/README.md")
    ports = [args.base_port + i for i in range(args.instances)]
    for p in ports + [args.lb_port]:
        if port_in_use(args.host, p):
            die(f"Port {p} is already in use. Is an old API or cluster still running? Stop it first.")

    args.log_dir.mkdir(parents=True, exist_ok=True)
    pool = max(2, args.db_connections // (2 * args.instances))  # pool_size = max_overflow = pool
    say(f"Starting {args.instances} API instances (database connections per instance: up to {pool * 2}, "
        f"total up to {pool * 2 * args.instances}).")

    procs: list[Managed] = []
    instances: list[Managed] = []
    for i, port in enumerate(ports, 1):
        env = dict(os.environ, PYTHONUNBUFFERED="1", INSTANCE_NAME=f"instance-{i}",
                   DB_POOL_SIZE=str(pool), DB_MAX_OVERFLOW=str(pool))
        cmd = [sys.executable, "-m", "uvicorn", "app.main:app", "--host", args.host, "--port", str(port)]
        if args.no_access_log:
            cmd.append("--no-access-log")
        m = Managed(f"instance-{i}", cmd, BACKEND, env, args.log_dir / f"instance-{i}.log", args.restart_delay, port)
        m.start()
        instances.append(m)
    procs += instances

    # wait for at least one instance to be healthy before starting the load balancer
    deadline = time.monotonic() + 60
    reported: set[str] = set()
    while time.monotonic() < deadline:
        for m in instances:
            if m.name not in reported and http_ready(args.host, m.port):
                reported.add(m.name)
                say(f"{m.name} is ready on port {m.port}")
        if reported:
            break
        if all(not m.alive() for m in instances):
            for m in instances:
                say(f"{m.name} log:\n{tail(m.log_path)}")
            for m in instances:
                m.stop()
            die("Every instance stopped right after starting. Check backend/.env (DATABASE_URL, JWT_SECRET) and that PostgreSQL is running. See the log lines above.")
        time.sleep(0.5)
    else:
        for m in instances:
            m.stop()
        die("No instance became ready within 60 seconds. Is PostgreSQL running? Check logs/instance-1.log")

    caddyfile = HERE / "Caddyfile.generated"
    caddyfile.write_text(build_caddyfile(args.host, args.lb_port, ports, args.policy, args.frontend_origin), encoding="utf-8")
    lb = Managed("load balancer", [caddy, "run", "--config", str(caddyfile), "--adapter", "caddyfile"], HERE,
                 dict(os.environ), args.log_dir / "caddy.log", args.restart_delay)
    lb.start()
    procs.append(lb)
    for _ in range(40):  # up to ~10 s
        if http_ready(args.host, args.lb_port, "/health"):
            break
        time.sleep(0.25)
    else:
        say(f"The load balancer did not answer. Log:\n{tail(lb.log_path, 12)}")
        for m in reversed(procs):
            m.stop()
        die("Could not start Caddy. See the log lines above and cluster/README.md")

    def shutdown(*_a) -> None:
        raise KeyboardInterrupt

    for name in ("SIGINT", "SIGTERM", "SIGBREAK"):  # Ctrl+C, a stop request, Ctrl+Break on Windows
        if hasattr(signal, name):
            signal.signal(getattr(signal, name), shutdown)

    print(f"""
  Load balancer:  http://localhost:{args.lb_port}        <- use this for the frontend and the load tests
  Instances:      {', '.join(f'{args.host}:{p}' for p in ports)}     (direct, for debugging only)
  Logs:           {args.log_dir}{os.sep}instance-N.log, caddy.log
  Policy:         {args.policy}.  Ctrl+C stops everything.
""", flush=True)

    start = time.monotonic()
    next_status = start + args.status_every
    next_chaos = start + args.chaos_every * random.uniform(0.7, 1.3) if args.chaos_every else None
    try:
        while True:
            time.sleep(0.5)
            now = time.monotonic()
            for m in procs:
                m.supervise(now)
            if next_chaos is not None and now >= next_chaos:
                healthy = [m for m in instances if m.alive() and http_ready(args.host, m.port)]
                if len(healthy) >= 2:  # never kill the last healthy instance
                    victim = random.choice(healthy)
                    say(f"CHAOS: killing {victim.name} (hard crash, no warning)")
                    victim.kill()
                next_chaos = now + args.chaos_every * random.uniform(0.7, 1.3)
            if now >= next_status:
                parts = []
                for m in instances:
                    if m.given_up:
                        parts.append(f"{m.name} GAVE UP")
                    elif m.alive() and http_ready(args.host, m.port):
                        parts.append(f"{m.name} up")
                    elif m.alive():
                        parts.append(f"{m.name} starting")
                    else:
                        parts.append(f"{m.name} DOWN")
                if http_ready(args.host, args.lb_port, "/health"):
                    lb_state = "up"
                elif lb.alive():
                    lb_state = "up, but no healthy instance to send traffic to"
                else:
                    lb_state = "DOWN"
                say(f"status: {' | '.join(parts)}   restarts={sum(m.restarts for m in instances)}   load balancer: {lb_state}")
                next_status = now + args.status_every
    except KeyboardInterrupt:
        say("Stopping everything...")
    finally:
        for m in reversed(procs):
            m.stop()
        end = time.monotonic() + 6
        while time.monotonic() < end and any(m.alive() for m in procs):
            time.sleep(0.2)
        for m in procs:
            m.kill()
        say("Stopped.")


if __name__ == "__main__":
    main()
